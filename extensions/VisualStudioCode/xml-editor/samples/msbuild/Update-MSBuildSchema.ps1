<#
.SYNOPSIS
    Regenerates schemas/ from the official MSBuild XML schema in dotnet/msbuild.

.DESCRIPTION
    Microsoft publishes the MSBuild schema (Microsoft.Build.xsd, Microsoft.Build.Core.xsd, and
    Microsoft.Build.CommonTypes.xsd) under the MIT license. This script downloads those files at a
    pinned release tag and derives an editor-oriented variant from them:

    - Namespace-neutral. The upstream schema targets
      http://schemas.microsoft.com/developer/msbuild/2003, which SDK-style projects
      (<Project Sdk="...">) do not declare. The Core and CommonTypes files are written without a
      target namespace, and two wrappers include them: Microsoft.Build.xsd for no-namespace
      projects, and Microsoft.Build.Namespaced.xsd, whose chameleon include places the same
      components in the 2003 namespace for legacy projects that declare it.
    - Open vocabulary. MSBuild accepts any property, item, metadata, or task name, but the upstream
      content models only admit the names they list. Skip wildcards are added to property groups,
      item groups, item definition groups, targets, and item types, and item types accept any
      attribute (metadata written as attributes), so custom names are not reported as errors while
      the listed names still drive completion and hover. An element that overlaps a wildcard
      violates XSD 1.0's Unique Particle Attribution rule but is valid XSD 1.1, where the declared
      element takes precedence over the wildcard.
    - Conditional, expression-valued properties. Every property accepts Condition and Label, and a
      value may be an expression such as $(Configuration). Properties upstream types as `boolean`
      or as an inline enumeration (which admits neither attributes nor expressions) are retyped so
      that the listed values are suggested, as upstream already does for `boolean`, but not enforced.

    Every edit is an exact-match replacement that must apply the expected number of times, so an
    upstream restructuring fails the script instead of silently producing a different schema.

.PARAMETER Tag
    The dotnet/msbuild release tag to read the schema from.
#>
[CmdletBinding()]
param(
    [string] $Tag = 'v18.11.0'
)

$ErrorActionPreference = 'Stop'

$upstreamNamespace = 'http://schemas.microsoft.com/developer/msbuild/2003'
$baseUri = "https://raw.githubusercontent.com/dotnet/msbuild/$Tag"
$schemaDirectory = Join-Path $PSScriptRoot 'schemas'
$includedDirectory = Join-Path $schemaDirectory 'MSBuild'
$wildcard = '<xs:any namespace="##any" processContents="skip"/>'

function Get-UpstreamText {
    param([string] $Path)

    Write-Host "Downloading $Path at $Tag"
    $text = (Invoke-WebRequest -Uri "$baseUri/$Path" -UseBasicParsing).Content
    if ($text -is [byte[]]) {
        $text = [System.Text.Encoding]::UTF8.GetString($text)
    }

    return $text.TrimStart([char] 0xFEFF) -replace "`r`n", "`n"
}

function Edit-Exactly {
    param(
        [string] $Text,
        [string] $Find,
        [string] $Replace,
        [int] $Count = 1,
        [string] $Description
    )

    $found = ([regex]::Matches($Text, [regex]::Escape($Find))).Count
    if ($found -ne $Count) {
        throw "Expected $Count occurrence(s) for '$Description' but found $found. The upstream schema changed; review the edits in this script."
    }

    return $Text.Replace($Find, $Replace)
}

function ConvertTo-NamespaceNeutral {
    param([string] $Text, [string] $FileName)

    # Drop the target namespace and the msb prefix from the schema element.
    $schemaTag = [regex]::Match($Text, '<xs:schema\b[^>]*>')
    if (-not $schemaTag.Success) {
        throw "$FileName has no xs:schema element."
    }

    $neutralTag = $schemaTag.Value `
        -replace "\s+targetNamespace=`"$([regex]::Escape($upstreamNamespace))`"", '' `
        -replace "\s+xmlns:msb=`"$([regex]::Escape($upstreamNamespace))`"", ''
    if ($neutralTag -match 'targetNamespace|xmlns:msb') {
        throw "$FileName declares its namespace in an unexpected form."
    }
    $Text = $Text.Remove($schemaTag.Index, $schemaTag.Length).Insert($schemaTag.Index, $neutralTag)

    # Unqualified QName references resolve to no namespace once the prefix is gone.
    $Text = [regex]::Replace(
        $Text,
        '\b(base|ref|type|substitutionGroup|itemType|memberTypes)="([^"]*)"',
        { param($match) "$($match.Groups[1].Value)=`"$($match.Groups[2].Value -replace '\bmsb:', '')`"" })

    if ($Text -match '="[^"]*\bmsb:') {
        throw "$FileName still references the msb prefix in an attribute value."
    }

    return $Text
}

function Get-Header {
    param([string] $UpstreamPath, [string[]] $Changes)

    $changeLines = ($Changes | ForEach-Object { "  - $_" }) -join "`n"
    return @"
<!--
  Generated by Update-MSBuildSchema.ps1 from dotnet/msbuild $Tag ($UpstreamPath).
  Copyright (c) .NET Foundation and contributors. Licensed under the MIT license; see LICENSE.txt.

  Changes from upstream:
$changeLines

  Do not edit by hand; change the script and regenerate.
-->

"@
}

New-Item -ItemType Directory -Path $includedDirectory -Force | Out-Null

# ------------------------------------------------------------------------------------------------
# Microsoft.Build.Core.xsd
# ------------------------------------------------------------------------------------------------
$core = ConvertTo-NamespaceNeutral (Get-UpstreamText 'src/MSBuild/MSBuild/Microsoft.Build.Core.xsd') 'Microsoft.Build.Core.xsd'

$core = Edit-Exactly $core `
    -Description 'PropertyGroupType admits any property' `
    -Find @'
        <xs:sequence minOccurs="0" maxOccurs="unbounded">
            <xs:element ref="Property"/>
        </xs:sequence>
'@ `
    -Replace @"
        <xs:choice minOccurs="0" maxOccurs="unbounded">
            <xs:element ref="Property"/>
            $wildcard
        </xs:choice>
"@

$core = Edit-Exactly $core `
    -Description 'ItemGroupType and ItemDefinitionGroupType admit any item' `
    -Count 2 `
    -Find @'
            <xs:element name="PostBuildEvent" type="PostBuildEventItem" />
        </xs:choice>
'@ `
    -Replace @"
            <xs:element name="PostBuildEvent" type="PostBuildEventItem" />
            $wildcard
        </xs:choice>
"@

$core = Edit-Exactly $core `
    -Description 'TargetType admits any task' `
    -Find @'
                    <xs:element ref="Task"/>
'@ `
    -Replace @"
                    <xs:element ref="Task"/>
                    $wildcard
"@

$simpleItemType = [regex]::Match($core, '<xs:complexType name="SimpleItemType">\s*(<xs:annotation>[\s\S]*?</xs:annotation>\s*)?')
if (-not $simpleItemType.Success) {
    throw 'SimpleItemType was not found in Microsoft.Build.Core.xsd.'
}
$core = $core.Insert(
    $simpleItemType.Index + $simpleItemType.Length,
    "<xs:sequence minOccurs=`"0`" maxOccurs=`"unbounded`">`n            $wildcard`n        </xs:sequence>`n        ")

# Metadata may be written as attributes: <Compile Include="a.cs" Link="b.cs" />.
$simpleItemTypeEnd = $core.IndexOf('</xs:complexType>', $simpleItemType.Index)
$core = $core.Insert($simpleItemTypeEnd, "    <xs:anyAttribute namespace=`"##any`" processContents=`"skip`"/>`n    ")

$core = Edit-Exactly $core `
    -Description 'shared property types are appended to Core' `
    -Find '</xs:schema>' `
    -Replace @'
    <!-- ======================================================================================= -->
    <!-- Added by Update-MSBuildSchema.ps1: the attributes every property accepts. -->
    <xs:attributeGroup name="PropertyAttributes">
        <xs:attribute name="Condition" type="xs:string" use="optional">
            <xs:annotation>
                <xs:documentation>Optional expression evaluated to determine whether the property is set</xs:documentation>
            </xs:annotation>
        </xs:attribute>
        <xs:attribute name="Label" type="xs:string" use="optional">
            <xs:annotation>
                <xs:documentation>Optional expression. Used to identify or order system and user elements</xs:documentation>
            </xs:annotation>
        </xs:attribute>
    </xs:attributeGroup>
    <!-- Added by Update-MSBuildSchema.ps1: a boolean-valued property that still accepts Condition and Label. -->
    <xs:complexType name="BooleanPropertyType">
        <xs:simpleContent>
            <xs:extension base="boolean">
                <xs:attributeGroup ref="PropertyAttributes"/>
            </xs:extension>
        </xs:simpleContent>
    </xs:complexType>
</xs:schema>
'@

$coreHeader = Get-Header 'src/MSBuild/MSBuild/Microsoft.Build.Core.xsd' @(
    'No target namespace; the msb: prefix is removed from type, base, ref, and substitutionGroup references.',
    'Skip wildcards in PropertyGroupType, ItemGroupType, ItemDefinitionGroupType, TargetType, and SimpleItemType admit custom properties, items, tasks, and metadata (XSD 1.1 overlapping wildcards).',
    'SimpleItemType accepts any attribute, for metadata written as attributes.',
    'Adds the PropertyAttributes attribute group and BooleanPropertyType.')

# ------------------------------------------------------------------------------------------------
# Microsoft.Build.CommonTypes.xsd
# ------------------------------------------------------------------------------------------------
$commonTypes = ConvertTo-NamespaceNeutral (Get-UpstreamText 'src/MSBuild/MSBuild/Microsoft.Build.CommonTypes.xsd') 'Microsoft.Build.CommonTypes.xsd'

# Boolean properties: the upstream `boolean` simple type suggests true/false, but a simple type
# admits no Condition attribute.
$booleanProperties = 0
$commonTypes = [regex]::Replace($commonTypes, '<xs:element\b[^>]*>', {
    param($match)
    if ($match.Value -match '\bsubstitutionGroup="Property"' -and $match.Value -match '\btype="boolean"') {
        $script:booleanProperties++
        return $match.Value -replace '\btype="boolean"', 'type="BooleanPropertyType"'
    }

    return $match.Value
})
if ($booleanProperties -eq 0) {
    throw 'No boolean-typed properties were found in Microsoft.Build.CommonTypes.xsd.'
}

# Enumerated properties: an inline enumeration rejects $(Expressions) and Condition alike. Each
# becomes a suggest-only union, upstream's own `boolean` pattern, extended with the property attributes.
$valueTypes = [System.Text.StringBuilder]::new()
$enumeratedProperties = 0
$commonTypes = [regex]::Replace(
    $commonTypes,
    '(<xs:element name="(?<name>[A-Za-z_][\w.-]*)" substitutionGroup="Property">(?<annotation>(?:(?!</xs:element>|<xs:simpleType>)[\s\S])*))<xs:simpleType>\s*<xs:restriction base="xs:string">(?<values>[\s\S]*?)</xs:restriction>\s*</xs:simpleType>(?<tail>\s*)</xs:element>',
    {
        param($match)
        $script:enumeratedProperties++
        $name = $match.Groups['name'].Value
        $values = ($match.Groups['values'].Value.Trim() -split '\n' | ForEach-Object { $_.Trim() }) -join "`n                    "
        [void] $script:valueTypes.Append(@"
    <xs:simpleType name="$($name)_PropertyValues">
        <xs:union memberTypes="non_empty_string">
            <xs:simpleType>
                <xs:restriction base="xs:string">
                    $values
                </xs:restriction>
            </xs:simpleType>
        </xs:union>
    </xs:simpleType>

"@)
        return @"
$($match.Groups[1].Value)<xs:complexType>
        <xs:simpleContent>
          <xs:extension base="$($name)_PropertyValues">
            <xs:attributeGroup ref="PropertyAttributes"/>
          </xs:extension>
        </xs:simpleContent>
      </xs:complexType>$($match.Groups['tail'].Value)</xs:element>
"@
    })

$untouched = [regex]::Matches($commonTypes, '<xs:element name="([^"]+)" substitutionGroup="Property">(?:(?!</xs:element>)[\s\S])*?<xs:simpleType>')
if ($enumeratedProperties -eq 0 -or $untouched.Count -gt 0) {
    throw "Enumerated properties were not all converted; still inline: $(($untouched | ForEach-Object { $_.Groups[1].Value }) -join ', ')"
}

$commonTypes = Edit-Exactly $commonTypes `
    -Description 'enumerated property value types are appended to CommonTypes' `
    -Find '</xs:schema>' `
    -Replace "    <!-- Added by Update-MSBuildSchema.ps1: suggested values of enumerated properties. -->`n$($valueTypes.ToString().TrimEnd())`n</xs:schema>"

# Upstream gap: the MSBuild task's RemoveProperties parameter (src/Tasks/MSBuild.cs) is not declared.
$commonTypes = Edit-Exactly $commonTypes `
    -Description 'MSBuild task declares RemoveProperties' `
    -Find @'
                    <xs:attribute name="RebaseOutputs" type="boolean" />
'@ `
    -Replace @'
                    <xs:attribute name="RebaseOutputs" type="boolean" />
                    <xs:attribute name="RemoveProperties" type="xs:string">
                        <xs:annotation>
                            <xs:documentation>Semicolon-separated list of global properties to remove before building the projects</xs:documentation>
                        </xs:annotation>
                    </xs:attribute>
'@

Write-Host "Retyped $booleanProperties boolean and $enumeratedProperties enumerated properties."
$commonTypesHeader = Get-Header 'src/MSBuild/MSBuild/Microsoft.Build.CommonTypes.xsd' @(
    'No target namespace; the msb: prefix is removed from type, base, ref, and substitutionGroup references.',
    "Boolean properties use BooleanPropertyType, and enumerated properties extend a suggest-only <Name>_PropertyValues union, so every property accepts Condition, Label, and `$(...) expressions.",
    'Declares the MSBuild task''s RemoveProperties parameter, which upstream omits.')

function Write-Schema {
    param([string] $Path, [string] $Header, [string] $Text)

    # Keep the XML declaration first; the provenance comment follows it.
    $declaration = [regex]::Match($Text, '^\s*<\?xml[^>]*\?>\s*')
    $body = if ($declaration.Success) { $Text.Substring($declaration.Length) } else { $Text }
    $content = "<?xml version=`"1.0`" encoding=`"utf-8`"?>`n$Header$body"
    if (-not $content.EndsWith("`n")) {
        $content += "`n"
    }

    [System.IO.File]::WriteAllText($Path, $content, [System.Text.UTF8Encoding]::new($false))
    Write-Host "Wrote $Path"
}

Write-Schema (Join-Path $includedDirectory 'Microsoft.Build.Core.xsd') $coreHeader $core
Write-Schema (Join-Path $includedDirectory 'Microsoft.Build.CommonTypes.xsd') $commonTypesHeader $commonTypes

# ------------------------------------------------------------------------------------------------
# Entry points
# ------------------------------------------------------------------------------------------------
$wrapperChanges = @(
    'Replaces upstream Microsoft.Build.xsd, which only includes CommonTypes and shows commented examples of custom items, properties, and tasks.')

Write-Schema (Join-Path $schemaDirectory 'Microsoft.Build.xsd') (Get-Header 'src/MSBuild/Microsoft.Build.xsd' $wrapperChanges) @'
<!-- For SDK-style and other projects that do not declare a namespace: <Project Sdk="Microsoft.NET.Sdk">. -->
<xs:schema xmlns:xs="http://www.w3.org/2001/XMLSchema" elementFormDefault="qualified">
    <xs:include schemaLocation="MSBuild/Microsoft.Build.CommonTypes.xsd"/>
</xs:schema>
'@

Write-Schema (Join-Path $schemaDirectory 'Microsoft.Build.Namespaced.xsd') (Get-Header 'src/MSBuild/Microsoft.Build.xsd' $wrapperChanges) @"
<!--
  For projects that declare xmlns="$upstreamNamespace". The included files have no
  target namespace, so this chameleon include places their components in the MSBuild namespace.
-->
<xs:schema xmlns:xs="http://www.w3.org/2001/XMLSchema"
           targetNamespace="$upstreamNamespace"
           elementFormDefault="qualified">
    <xs:include schemaLocation="MSBuild/Microsoft.Build.CommonTypes.xsd"/>
</xs:schema>
"@

$license = (Invoke-WebRequest -Uri "$baseUri/LICENSE" -UseBasicParsing).Content
[System.IO.File]::WriteAllText((Join-Path $schemaDirectory 'LICENSE.txt'), ($license -replace "`r`n", "`n"), [System.Text.UTF8Encoding]::new($false))
Write-Host "Wrote $(Join-Path $schemaDirectory 'LICENSE.txt')"
